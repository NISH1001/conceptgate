"""Write appendix_prompts.tex from the prompt sets, lexicon, and token baskets in scripts/.

Run from the repo root: python docs/preprint/make_appendix_prompts.py
"""
import ast
import re

OUT = "docs/preprint/appendix_prompts.tex"
src = open("scripts/eval_gate.py").read()
chk = open("scripts/eval_behaviour_check.py").read()
def grab(text, name):
    for node in ast.parse(text).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == name:
            return ast.literal_eval(node.value)
    raise KeyError(name)
def esc(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}", "’": "'"}
    return "".join(rep.get(c, c) for c in s)
def enum(items):
    return "\\begin{enumerate}[nosep,leftmargin=*,label=\\arabic*.]\n" + "\n".join(f"  \\item {esc(x)}" for x in items) + "\n\\end{enumerate}\n"
def inline(items):
    seen = []
    for x in items:
        if esc(x) not in seen:
            seen.append(esc(x))
    return ", ".join("``" + x + "''" for x in seen)
out = ["% Generated by docs/preprint/make_appendix_prompts.py from scripts/eval_gate.py,\n% scripts/eval_behaviour_check.py, and scripts/eval_prompting_baseline.py. Do not edit by hand.\n"]
out.append("\\subsection{Few-shot fit pools for the jailbreak write concept}\n")
out.append("Each resample draws eight prompts per side from these pools of sixteen (\\texttt{scripts/eval\\_gate.py}, \\texttt{FIT\\_POS} and \\texttt{FIT\\_NEG}).\n\n")
out.append("\\paragraph{Positives (override framings, no request).}\n{\\footnotesize\n" + enum(grab(src, "FIT_POS")) + "}\n")
out.append("\\paragraph{Negatives (short benign requests).}\n{\\footnotesize\n" + enum(grab(src, "FIT_NEG")) + "}\n")
out.append("\\subsection{Gate test sets (\\cref{sec:formatting,sec:lever,sec:register})}\n")
out.append("\\paragraph{Held-out framed attacks (\\texttt{JB\\_TEST}).}\n{\\footnotesize\n" + enum(grab(src, "JB_TEST")) + "}\n")
out.append("\\paragraph{In-register benign requests (\\texttt{BN\\_TEST}).}\n{\\footnotesize\n" + enum(grab(src, "BN_TEST")) + "}\n")
out.append("\\subsection{Harmful requests for the dose study (\\cref{sec:dose})}\n")
out.append("Each of the 120 held-out jailbreak templates gets one of these twelve requests appended. The twelve are also the bare requests.\n{\\footnotesize\n" + enum(grab(src, "HARM_REQUESTS")) + "}\n")
out.append("\\subsection{Refusal lexicon}\n")
out.append("A continuation counts as a refusal if its lower-cased text contains one of these strings: {\\footnotesize " + inline(grab(src, "REFUSAL")) + ".}\n\n")
out.append("\\subsection{First-token baskets (\\cref{sec:lever,sec:dose})}\n")
out.append("The statistic uses the first token of each string; distinct first tokens count once, so several strings here share the token ``I''. \\textbf{Refusal:} {\\footnotesize " + inline(grab(src, "REFUSAL_FIRST")) + ".} \\textbf{Compliance:} {\\footnotesize " + inline(grab(src, "COMPLY_FIRST")) + ".}\n\n")
out.append("\\subsection{Fixed continuations for the teacher-forced score (\\cref{sec:lever,sec:instrument})}\n")
out.append("\\textbf{Refusal:} {\\footnotesize " + inline(grab(chk, "REFUSAL_CONT")) + ".} \\textbf{Compliance:} {\\footnotesize " + inline(grab(chk, "COMPLY_CONT")) + ".}\n\n")
base = open("scripts/eval_prompting_baseline.py").read()
sysp = grab(base, "SYSTEM")
out.append("\\subsection{System prompts for the prompting baseline (\\cref{tab:prompting})}\n")
out.append("\\textbf{Refuse:} {\\footnotesize ``" + esc(sysp["refuse"]) + "''} \\textbf{Comply:} {\\footnotesize ``" + esc(sysp["comply"]) + "''} The default arm uses no system message.\n\n")
out.append("The topical few-shot sets and keyword lists (\\cref{sec:topical}) are in \\texttt{scripts/eval\\_steering.py}.\n")
tex = "".join(out)
# keep \cref out of PDF bookmarks
tex = re.sub(r"^(\\subsection\{.*?) \((\\cref\{[^}]*\})\)\}", r"\1\\texorpdfstring{ (\2)}{}}", tex, flags=re.M)
open(OUT, "w").write(tex)
